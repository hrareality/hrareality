const WITHDRAWAL_FORM_TITLE = "Příloha č. 3 — Vzorový formulář pro odstoupení od smlouvy";

/**
 * Formulář v Příloze č. 3 musí jít stáhnout jako PDF, ne jen přečíst na stránce
 * (aby ho spotřebitel mohl vyplnit a poslat) — viz klientský požadavek.
 *
 * jsPDF (dynamický import, ať nezvětšuje hlavní bundle) se standardními fonty
 * (Helvetica) NEUMÍ českou diakritiku — otestováno, "číslo" vyjde jako " íslo",
 * "přizpůsobené" jako "pYizposo..." Proto se embeduje Noto Sans (SIL OFL licence,
 * volně distribuovatelná), ale jen jako ořezaný subset (Latin + Latin Extended-A +
 * pár interpunkčních znaků) — 22 KB/řez místo original ~556 KB. Font se fetchuje
 * z public/fonts/ až při kliknutí (viz public/fonts/README.md pro regeneraci).
 */
async function downloadWithdrawalForm() {
  const section = SECTIONS.find((s) => s.title === WITHDRAWAL_FORM_TITLE);
  if (!section) return;

  function arrayBufferToBase64(buf: ArrayBuffer) {
    let binary = "";
    const bytes = new Uint8Array(buf);
    const chunkSize = 0x8000;
    for (let i = 0; i < bytes.length; i += chunkSize) {
      binary += String.fromCharCode(...bytes.subarray(i, i + chunkSize));
    }
    return btoa(binary);
  }

  const [{ jsPDF }, regularBuf, boldBuf] = await Promise.all([
    import("jspdf"),
    fetch("/fonts/notosans-regular.ttf").then((r) => r.arrayBuffer()),
    fetch("/fonts/notosans-bold.ttf").then((r) => r.arrayBuffer()),
  ]);

  const doc = new jsPDF({ unit: "mm", format: "a4" });
  doc.addFileToVFS("NotoSans-Regular.ttf", arrayBufferToBase64(regularBuf));
  doc.addFont("NotoSans-Regular.ttf", "NotoSans", "normal");
  doc.addFileToVFS("NotoSans-Bold.ttf", arrayBufferToBase64(boldBuf));
  doc.addFont("NotoSans-Bold.ttf", "NotoSans", "bold");

  const marginX = 20;
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const maxWidth = pageWidth - marginX * 2;
  const lineHeight = 6;
  let y = 22;

  doc.setFont("NotoSans", "bold");
  doc.setFontSize(13);
  for (const line of doc.splitTextToSize(section.title, maxWidth)) {
    doc.text(line, marginX, y);
    y += 7;
  }
  y += 4;

  doc.setFont("NotoSans", "normal");
  doc.setFontSize(10.5);
  for (const paragraph of section.body.split("\n")) {
    // "☐" (BALLOT BOX) chybí v subsetovaném fontu (Noto Sans Regular ho vůbec
    // nemá — dingbaty jsou v samostatném "Noto Sans Symbols"), takže se místo
    // spoléhání na font kreslí jako skutečný vektorový čtvereček.
    const isCheckbox = paragraph.trimStart().startsWith("☐");
    const text = isCheckbox ? paragraph.trimStart().slice(1).trim() : paragraph;
    const indent = isCheckbox ? 6 : 0;
    const wrapped = text.trim() === "" ? [""] : doc.splitTextToSize(text, maxWidth - indent);
    wrapped.forEach((line: string, i: number) => {
      if (y > pageHeight - 20) {
        doc.addPage();
        y = 22;
      }
      if (isCheckbox && i === 0) {
        doc.rect(marginX, y - 3.2, 3.5, 3.5);
      }
      doc.text(line, marginX + indent, y);
      y += lineHeight;
    });
  }

  doc.save("formular-odstoupeni-od-smlouvy.pdf");
}

